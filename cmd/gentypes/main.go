// Command gentypes generates TypeScript types for the unified GraphQL API.
//
// graph/schema.graphqls is the single source of truth: gqlgen generates the Go
// types from it, and this command generates web/src/lib/graphql-types.ts.
// Run with -check to fail when the checked-in file is stale.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/vektah/gqlparser/v2"
	"github.com/vektah/gqlparser/v2/ast"

	"github.com/wricardo/drbrain/graph/merge"
)

const header = `// Code generated by cmd/gentypes from graph/schema.graphqls. DO NOT EDIT.
//
// The GraphQL schema is the single source of truth: gqlgen generates the Go
// types from it and this file generates the TypeScript. Regenerate with
// ` + "`go run ./cmd/gentypes`" + `.

/* eslint-disable */

`

func main() {
	out := flag.String("o", "", "output file (default: <repo>/web/src/lib/graphql-types.ts)")
	check := flag.Bool("check", false, "verify the output is up to date instead of writing")
	flag.Parse()

	root, err := merge.RepoRoot()
	if err != nil {
		fail(err)
	}
	target := *out
	if target == "" {
		target = filepath.Join(root, "web", "src", "lib", "graphql-types.ts")
	}
	src, err := generate(filepath.Join(root, merge.SchemaPath))
	if err != nil {
		fail(err)
	}
	if *check {
		existing, err := os.ReadFile(target)
		if err != nil {
			fail(err)
		}
		if string(existing) != src {
			fail(fmt.Errorf("%s is stale: run go run ./cmd/gentypes", target))
		}
		fmt.Printf("%s is current\n", target)
		return
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		fail(err)
	}
	if err := os.WriteFile(target, []byte(src), 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s\n", target)
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "gentypes: %v\n", err)
	os.Exit(1)
}

func generate(path string) (string, error) {
	sdl, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("read schema: %w", err)
	}
	schema, err := gqlparser.LoadSchema(&ast.Source{Name: path, Input: string(sdl)})
	if err != nil {
		return "", fmt.Errorf("parse schema: %w", err)
	}

	var b strings.Builder
	b.WriteString(header)

	for _, op := range []struct {
		name string
		def  *ast.Definition
	}{
		{"Query", schema.Query},
		{"Mutation", schema.Mutation},
		{"Subscription", schema.Subscription},
	} {
		if op.def == nil {
			continue
		}
		b.WriteString("export interface " + op.name + " {\n")
		for _, f := range op.def.Fields {
			if strings.HasPrefix(f.Name, "__") {
				continue
			}
			b.WriteString(fieldLine(f))
		}
		b.WriteString("}\n\n")
	}

	var enums, objects, inputs []string
	for name, def := range schema.Types {
		if strings.HasPrefix(name, "__") || def.BuiltIn {
			continue
		}
		switch def.Kind {
		case ast.Enum:
			enums = append(enums, name)
		case ast.Object:
			if name != "Query" && name != "Mutation" && name != "Subscription" {
				objects = append(objects, name)
			}
		case ast.InputObject:
			inputs = append(inputs, name)
		}
	}
	for _, list := range [][]string{enums, objects, inputs} {
		sort.Strings(list)
	}

	for _, name := range enums {
		b.WriteString(renderEnum(schema.Types[name]))
	}
	for _, name := range objects {
		b.WriteString(renderObject(schema.Types[name]))
	}
	for _, name := range inputs {
		b.WriteString(renderObject(schema.Types[name]))
	}
	return b.String(), nil
}

func renderObject(def *ast.Definition) string {
	var b strings.Builder
	writeComment(&b, def.Description)
	b.WriteString("export interface " + def.Name + " {\n")
	for _, f := range def.Fields {
		if strings.HasPrefix(f.Name, "__") {
			continue
		}
		b.WriteString(fieldLine(f))
	}
	b.WriteString("}\n\n")
	return b.String()
}

func renderEnum(def *ast.Definition) string {
	var b strings.Builder
	writeComment(&b, def.Description)
	parts := make([]string, 0, len(def.EnumValues))
	for _, v := range def.EnumValues {
		parts = append(parts, "'"+v.Name+"'")
	}
	b.WriteString("export type " + def.Name + " = " + strings.Join(parts, " | ") + ";\n\n")
	return b.String()
}

func writeComment(b *strings.Builder, desc string) {
	desc = strings.TrimSpace(desc)
	if desc == "" {
		return
	}
	b.WriteString("/**\n")
	for _, line := range strings.Split(desc, "\n") {
		b.WriteString(" * " + line + "\n")
	}
	b.WriteString(" */\n")
}

func fieldLine(f *ast.FieldDefinition) string {
	var b strings.Builder
	if f.Description != "" {
		b.WriteString("\t/** " + strings.ReplaceAll(strings.TrimSpace(f.Description), "\n", " ") + " */\n")
	}
	ts := tsType(f.Type)
	if len(f.Arguments) > 0 {
		var args []string
		for _, a := range f.Arguments {
			optional := true
			if a.Type != nil && a.Type.NonNull && a.DefaultValue == nil {
				optional = false
			}
			name := a.Name
			if optional {
				name += "?"
			}
			args = append(args, name+": "+tsType(a.Type))
		}
		ts = fmt.Sprintf("(args: { %s }) => %s", strings.Join(args, "; "), ts)
	}
	if f.DefaultValue != nil {
		ts = tsType(f.Type)
	}
	b.WriteString(fmt.Sprintf("\t%s: %s;\n", f.Name, ts))
	return b.String()
}

func tsType(t *ast.Type) string {
	if t == nil {
		return "unknown"
	}
	var base string
	if t.Elem != nil {
		base = tsType(t.Elem) + "[]"
	} else {
		switch t.NamedType {
		case "String", "ID":
			base = "string"
		case "Int", "Float":
			base = "number"
		case "Boolean":
			base = "boolean"
		case "Time":
			base = "string"
		default:
			base = t.NamedType
		}
	}
	if t.NonNull {
		return base
	}
	return base + " | null"
}
