// Command gentypes generates TypeScript types for the GraphQL API from the
// schema itself.
//
// The schema (graph/schema.graphqls) is the single source of truth: gqlgen
// generates the Go types from it, and this command generates the TypeScript from
// it. Neither side hand-maintains a copy, so the client cannot describe a shape
// the server does not serve.
//
// Run with no arguments to write frontend/src/lib/api-types.ts. Run with -check
// to fail when the file on disk is stale; `make check` and `go test ./...` both
// do that, so a schema change without regeneration breaks the build.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/vektah/gqlparser/v2"
	"github.com/vektah/gqlparser/v2/ast"
)

const (
	schemaPath = "graph/schema.graphqls"
	header     = `// Code generated by cmd/gentypes from graph/schema.graphqls. DO NOT EDIT.
//
// The GraphQL schema is the single source of truth: gqlgen generates the Go
// types from it and this file generates the TypeScript. Regenerate with
// ` + "`make types`" + `.

/* eslint-disable */

`
)

func main() {
	out := flag.String("o", "frontend/src/lib/api-types.ts", "output file")
	check := flag.Bool("check", false, "verify the output is up to date instead of writing")
	flag.Parse()

	src, err := generate(schemaPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "gentypes: %v\n", err)
		os.Exit(1)
	}

	if *check {
		existing, err := os.ReadFile(*out)
		if err != nil {
			fmt.Fprintf(os.Stderr, "gentypes: read %s: %v\n", *out, err)
			os.Exit(1)
		}
		if string(existing) != src {
			fmt.Fprintf(os.Stderr, "gentypes: %s is stale; run `make types`\n", *out)
			os.Exit(1)
		}
		fmt.Printf("gentypes: %s is up to date\n", *out)
		return
	}

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "gentypes: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(src), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gentypes: write %s: %v\n", *out, err)
		os.Exit(1)
	}
	fmt.Printf("gentypes: wrote %s\n", *out)
}

// generate parses the schema and renders the TypeScript file.
func generate(path string) (string, error) {
	sdl, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("read schema: %w", err)
	}
	schema, err := gqlparser.LoadSchema(&ast.Source{Name: path, Input: string(sdl)})
	if err != nil {
		return "", fmt.Errorf("parse schema: %w", err)
	}

	var b strings.Builder
	b.WriteString(header)

	// Root operation types.
	b.WriteString("export interface Query {\n")
	for _, f := range schema.Query.Fields {
		if strings.HasPrefix(f.Name, "__") {
			continue // introspection, not part of the game contract
		}
		b.WriteString(fieldLine(f))
	}
	b.WriteString("}\n\n")

	if schema.Mutation != nil {
		b.WriteString("export interface Mutation {\n")
		for _, f := range schema.Mutation.Fields {
			b.WriteString(fieldLine(f))
		}
		b.WriteString("}\n\n")
	}

	// Enums, sorted for a stable diff.
	var enums []string
	for name, def := range schema.Types {
		// Skip GraphQL's built-in introspection types: they are part of the
		// protocol, not of this game's contract.
		if strings.HasPrefix(name, "__") {
			continue
		}
		if def.Kind == ast.Enum {
			enums = append(enums, name)
		}
	}
	sort.Strings(enums)
	for _, name := range enums {
		def := schema.Types[name]
		b.WriteString(renderEnum(def))
	}

	// Object types (except the roots and the introspection types).
	var objects []string
	for name, def := range schema.Types {
		if def.Kind != ast.Object || name == "Query" || name == "Mutation" || name == "Subscription" {
			continue
		}
		if strings.HasPrefix(name, "__") || def.BuiltIn {
			continue
		}
		objects = append(objects, name)
	}
	sort.Strings(objects)
	for _, name := range objects {
		def := schema.Types[name]
		b.WriteString(renderObject(def))
	}

	return b.String(), nil
}

// renderObject renders one object type as an interface.
func renderObject(def *ast.Definition) string {
	var b strings.Builder
	if def.Description != "" {
		b.WriteString("/**\n")
		for _, line := range strings.Split(strings.TrimSpace(def.Description), "\n") {
			b.WriteString(" * " + line + "\n")
		}
		b.WriteString(" */\n")
	}
	b.WriteString("export interface " + def.Name + " {\n")
	for _, f := range def.Fields {
		if strings.HasPrefix(f.Name, "__") {
			continue
		}
		b.WriteString(fieldLine(f))
	}
	b.WriteString("}\n\n")
	return b.String()
}

// renderEnum renders one enum as a string union. GraphQL enums are sent as their
// uppercase names, so the union uses those literal values.
func renderEnum(def *ast.Definition) string {
	var b strings.Builder
	if def.Description != "" {
		b.WriteString("/**\n")
		for _, line := range strings.Split(strings.TrimSpace(def.Description), "\n") {
			b.WriteString(" * " + line + "\n")
		}
		b.WriteString(" */\n")
	}
	parts := make([]string, 0, len(def.EnumValues))
	for _, v := range def.EnumValues {
		parts = append(parts, "'"+v.Name+"'")
	}
	b.WriteString("export type " + def.Name + " = " + strings.Join(parts, " | ") + ";\n\n")
	return b.String()
}

// fieldLine renders one field, including its description and nullability.
func fieldLine(f *ast.FieldDefinition) string {
	var b strings.Builder
	if f.Description != "" {
		b.WriteString("\t/** " + strings.ReplaceAll(strings.TrimSpace(f.Description), "\n", " ") + " */\n")
	}
	ts := tsType(f.Type)
	// A field with arguments is a function on the client. Only the root types
	// have arguments here, and those are already rendered as their own fields,
	// so a non-root field with args is a schema mistake worth surfacing.
	if len(f.Arguments) > 0 {
		var args []string
		for _, a := range f.Arguments {
			// An argument is optional only when it is nullable or has a default.
			// Checking the type's nullability (not its name) is what makes
			// `id: ID!` required on the client.
			optional := true
			if a.Type != nil && a.Type.NonNull && a.DefaultValue == nil {
				optional = false
			}
			name := a.Name
			if optional {
				name += "?"
			}
			args = append(args, name+": "+tsType(a.Type))
		}
		ts = fmt.Sprintf("(args: { %s }) => %s", strings.Join(args, "; "), ts)
	}
	b.WriteString(fmt.Sprintf("\t%s: %s;\n", f.Name, ts))
	return b.String()
}

// tsType maps a GraphQL type to TypeScript, honouring nullability.
func tsType(t *ast.Type) string {
	if t == nil {
		return "unknown"
	}
	var base string
	if t.Elem != nil {
		// A list: [T] or [T!]
		base = tsType(t.Elem) + "[]"
	} else {
		switch t.NamedType {
		case "String", "ID":
			base = "string"
		case "Int", "Float":
			base = "number"
		case "Boolean":
			base = "boolean"
		case "Time":
			base = "string"
		default:
			base = t.NamedType
		}
	}
	if t.NonNull {
		return base
	}
	return base + " | null"
}
