package merge

import (
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

// GQLGenConfig returns graph/gqlgen.yml for the merged schema.
//
// Every game-defined type binds to the model type its own gqlgen package
// already generated, so resolvers and conversions keep working unchanged. The
// four namespace Query/Mutation types bind to that game's *graph.Resolver and
// mark every field resolver-driven; the flat Subscription roots use gqlgen's
// default root subscription resolvers.
func GQLGenConfig(root string) ([]byte, error) {
	type entry struct {
		name  string
		model string
		// fields holds resolver-driven fields for this type.
		fields []string
	}
	var entries []entry

	// Custom field resolvers that live in the game's graph package rather than
	// its model struct. These mirror the per-game gqlgen.yml files.
	custom := map[string][]string{
		"Delivery_LedgerView": {"months", "cashEntries", "cars"},
		"Delivery_Snapshot":   {"orders", "openOrders"},
		"Motor_Map":           {"builtin", "status", "ownedByMe"},
		"Tesla_GameState":     {"grid"},
		"Tesla_GameMap":       {"layout"},
	}

	for _, g := range Games {
		defs, err := parse(filepath.Join(root, g.Dir, "graph", "schema.graphqls"))
		if err != nil {
			return nil, err
		}
		for _, d := range defs {
			if d.Name == "Time" {
				continue
			}
			name := g.Name + "_" + d.Name
			if isRoot(d.Name) {
				if d.Name == "Subscription" {
					continue // flat root fields, no model
				}
				var fields []string
				for _, f := range d.Fields {
					fields = append(fields, f.Name)
				}
				entries = append(entries, entry{
					name:   name,
					model:  "github.com/wricardo/drbrain/" + g.ResolverPkg + ".Resolver",
					fields: fields,
				})
				continue
			}
			entries = append(entries, entry{
				name:   name,
				model:  "github.com/wricardo/drbrain/" + g.ModelPkg + "." + d.Name,
				fields: custom[name],
			})
		}
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].name < entries[j].name })

	var b strings.Builder
	b.WriteString("# Code generated by cmd/merge-schema. DO NOT EDIT.\n\n")
	b.WriteString("schema:\n  - schema.graphqls\n\n")
	b.WriteString("skip_mod_tidy: true\n\n")
	b.WriteString("exec:\n  filename: generated/generated.go\n  package: generated\n\n")
	b.WriteString("model:\n  filename: model/models_gen.go\n  package: model\n\n")
	b.WriteString("resolver:\n  layout: follow-schema\n  dir: .\n  package: graph\n  filename_template: \"{name}.resolvers.go\"\n\n")
	b.WriteString("models:\n")
	for _, scalar := range []struct {
		name, model string
	}{
		{"ID", "github.com/99designs/gqlgen/graphql.ID"},
		{"String", "github.com/99designs/gqlgen/graphql.String"},
		{"Int", "github.com/99designs/gqlgen/graphql.Int"},
		{"Float", "github.com/99designs/gqlgen/graphql.Float"},
		{"Boolean", "github.com/99designs/gqlgen/graphql.Boolean"},
		{"Time", "github.com/99designs/gqlgen/graphql.Time"},
	} {
		fmt.Fprintf(&b, "  %s:\n    model: %s\n", scalar.name, scalar.model)
	}
	for _, e := range entries {
		fmt.Fprintf(&b, "  %s:\n    model: %s\n", e.name, e.model)
		if len(e.fields) == 0 {
			continue
		}
		b.WriteString("    fields:\n")
		for _, f := range e.fields {
			fmt.Fprintf(&b, "      %s:\n        resolver: true\n", f)
		}
	}
	return []byte(b.String()), nil
}
